"""Converts wildbg's trained networks (ONNX) into the TypeScript modules games/backgammon/wildbg/contact.ts and
race.ts (E-039). The networks are by Carsten Wenderdel, CC0-1.0: https://github.com/carsten-wenderdel/wildbg-training,
as copied to wildbg's "nets" branch (data/0017/contact.onnx, data/0016/race.onnx).
  pip install onnx numpy
  python3 scripts/wildbg-nets.py path/to/wildbg/neural-nets
Each module is one base64 string of float32 little-endian numbers: per layer the weights [out][in], then the biases.
"""
import base64
import sys
from pathlib import Path

import onnx
from onnx import numpy_helper

NETS = {
    "contact": ("data/0017/contact.onnx", "HardSigmoid (x / 6 + 0.5, clamped to 0..1)", 202),
    "race": ("data/0016/race.onnx", "ReLU", 186),
}
ORDER = [f"base_model.{layer}.{kind}" for layer in ("hidden1", "hidden2", "hidden3", "output") for kind in ("weight", "bias")]
src = Path(sys.argv[1])
out = Path(__file__).resolve().parent.parent / "games" / "backgammon" / "wildbg"
for name, (origin, activation, inputs) in NETS.items():
    model = onnx.load(src / f"{name}.onnx")
    init = {t.name: numpy_helper.to_array(t).astype("<f4") for t in model.graph.initializer}
    shapes = ", ".join(f"{k.split('.')[1]} {list(init[k].shape)}" for k in ORDER[::2])
    b64 = base64.b64encode(b"".join(init[k].tobytes() for k in ORDER)).decode()
    body = "\n".join(b64[i : i + 120] for i in range(0, len(b64), 120))
    (out / f"{name}.ts").write_text(
        f"""// wildbg's {name} network, by Carsten Wenderdel: {origin} of
// https://github.com/carsten-wenderdel/wildbg-training (CC0-1.0, public domain). Generated by scripts/wildbg-nets.py:
// float32 little-endian in base64, per layer the weights [out][in] then the biases; {inputs} inputs; layers {shapes};
// hidden activation {activation}, softmax over win normal, gammon, backgammon, lose the same. Line breaks are ignored.
export default `
{body}
`;
"""
    )
    print(name, len(b64), "base64 characters")
